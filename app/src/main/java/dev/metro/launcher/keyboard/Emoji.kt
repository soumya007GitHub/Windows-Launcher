    // ------------------------------------------------------------------ recent

    private const val PREFS = "metro_keyboard"
    private const val KEY_RECENT = "recent_emoji"
    private const val MAX_RECENT = 32

    fun recent(context: Context): List<String> =
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .getString(KEY_RECENT, null)
            ?.split('\n')
            ?.filter { it.isNotEmpty() }
            .orEmpty()

    fun remember(context: Context, emoji: String) {
        val updated = (listOf(emoji) + recent(context).filter { it != emoji }).take(MAX_RECENT)
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .edit()
            .putString(KEY_RECENT, updated.joinToString("\n"))
            .apply()
    }
